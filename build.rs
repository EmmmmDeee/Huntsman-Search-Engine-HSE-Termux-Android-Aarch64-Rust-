//! Build script: generate a compile-time manifest of every Rust source file in
//! `src/`, so the running binary can report its complete file inventory (path +
//! line count) in the debug bundle — a build fingerprint that "incorporates all
//! files". Pure std (no build-dependencies, preserving the no-native-deps Termux
//! build); runs on the HOST during a cross-build, walking the source tree that is
//! present at build time. Output is sorted by path so the generated constant —
//! and therefore the debug bundle — is byte-deterministic.
//!
//! The same manifest carries `LOGIC_FINGERPRINT` (see [`logic_fingerprint`]), the
//! content hash the inter-scan cache keys on so an upgrade never replays an
//! answer computed by the logic it replaced.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    emit_build_provenance();

    let mut files: Vec<(String, u32)> = Vec::new();
    collect(Path::new("src"), &mut files);
    files.sort(); // deterministic order (by relative path)

    let mut out = String::new();
    out.push_str("// @generated by build.rs — do not edit.\n");
    out.push_str(
        "/// Every Rust source file in `src/` at build time: (relative path, line count).\n",
    );
    out.push_str("pub const SOURCE_FILES: &[(&str, u32)] = &[\n");
    let mut total: u32 = 0;
    for (path, lines) in &files {
        let _ = writeln!(out, "    ({path:?}, {lines}),");
        total = total.saturating_add(*lines);
    }
    out.push_str("];\n");
    let _ = writeln!(
        out,
        "/// Total source lines across {} files.\npub const SOURCE_TOTAL_LINES: u32 = {total};",
        files.len()
    );
    let fingerprint = logic_fingerprint();
    let _ = writeln!(
        out,
        "/// FNV-1a 64 of every file that can change a module's answer (build.rs\n\
         /// `logic_fingerprint`). Prefixes every inter-scan cache key, so an answer\n\
         /// archived by different module logic is a miss (REQ-CACHE-002).\n\
         pub const LOGIC_FINGERPRINT: &str = \"{fingerprint:016x}\";"
    );

    let dir = std::env::var("OUT_DIR").expect("OUT_DIR set by cargo");
    std::fs::write(Path::new(&dir).join("source_manifest.rs"), out)
        .expect("write source_manifest.rs");

    println!("cargo:rerun-if-changed=build.rs");
    // NB: `collect` and `collect_logic` already emitted a `rerun-if-changed` for
    // every file AND every directory they walked. The Cargo reference says a
    // directory path makes cargo "scan the entire directory for any
    // modifications" (doc.rust-lang.org/cargo/reference/build-scripts.html), so
    // the per-file and per-subdirectory watches are a redundant superset of the
    // root-directory ones — kept because they cost nothing and do not depend on
    // how a given cargo version scans a directory. An earlier version of this
    // comment claimed cargo watches only a directory's DIRECT children; the
    // reference says otherwise (REQ-CACHE-002).
}

/// Stamp the exact source revision into the binary as `HSE_GIT_SHA` /
/// `HSE_GIT_DIRTY`.
///
/// The version string alone cannot identify a build. `Cargo.toml`'s version
/// changes only on a deliberate bump, so every commit merged to `main` between
/// two bumps produces a binary reporting the SAME version as the release — which
/// is precisely how the installer and the auto-updater came to "succeed" while
/// leaving a device several commits behind. A commit SHA is the only identifier
/// that distinguishes them, so `install.sh` can refuse a prebuilt that is not the
/// revision it was asked for.
///
/// Resolution order:
/// 1. `HSE_BUILD_SHA` — for builds from a source archive with no `.git`
///    (CI passes `github.sha`). Also the escape hatch for reproducible builds.
/// 2. `git rev-parse HEAD` in the source tree.
/// 3. `unknown` — never fabricated. Consumers treat `unknown` as "cannot verify"
///    and fall back to building from source rather than trusting the binary.
fn emit_build_provenance() {
    println!("cargo:rerun-if-env-changed=HSE_BUILD_SHA");
    // A checkout rewrites `.git/HEAD`; a COMMIT on a branch does not — HEAD is
    // then the symbolic `ref: refs/heads/<branch>`, byte-identical before and
    // after, and only the ref file it points at changes. Watching HEAD alone
    // therefore left this stamp stale across commits: a binary rebuilt after a
    // commit kept reporting the previous SHA, and `install.sh` — which compares
    // `hse build-sha` against the revision it installed — would misjudge it.
    // So resolve the symbolic ref and watch its target too, plus the target's
    // directory (a loose ref file APPEARS there on the first commit after
    // `git pack-refs`, and a directory watch sees its direct children change)
    // and `packed-refs` (where the ref lives until then).
    // `Some("")` is a meaningful result here (a clean `git status --porcelain`),
    // so success-with-empty-output must be distinguishable from failure.
    let git = |args: &[&str]| -> Option<String> {
        let out = Command::new("git").args(args).output().ok()?;
        out.status
            .success()
            .then(|| String::from_utf8_lossy(&out.stdout).trim().to_string())
    };

    // Where git keeps HEAD and the refs. In a `git worktree` checkout `.git` is
    // a FILE (a `gitdir:` pointer), so hardcoded `.git/…` paths exist nowhere,
    // every guard below skipped, and the stamp never refreshed on a commit made
    // there. `--git-dir` is the per-checkout directory (HEAD, ORIG_HEAD,
    // logs/HEAD); `--git-common-dir` the shared one (refs/, packed-refs). In an
    // ordinary checkout both are `.git`, so this changes nothing there; when
    // git is absent, `.git` is assumed, which is exactly the previous behaviour.
    let git_dir = git(&["rev-parse", "--git-dir"])
        .filter(|d| !d.is_empty())
        .unwrap_or_else(|| ".git".to_string());
    let common_dir = git(&["rev-parse", "--git-common-dir"])
        .filter(|d| !d.is_empty())
        .unwrap_or_else(|| git_dir.clone());

    // `logs/HEAD` is the reflog every movement of HEAD appends to — commit,
    // checkout, reset, merge — whatever the ref layout (loose, packed,
    // detached), so it is the most direct signal that the stamped revision may
    // have changed. Guarded like the rest: absent when reflogs are disabled.
    for p in [
        format!("{git_dir}/HEAD"),
        format!("{git_dir}/ORIG_HEAD"),
        format!("{git_dir}/logs/HEAD"),
        format!("{common_dir}/packed-refs"),
    ] {
        if Path::new(&p).exists() {
            println!("cargo:rerun-if-changed={p}");
        }
    }
    if let Some(target) = std::fs::read_to_string(format!("{git_dir}/HEAD"))
        .ok()
        .and_then(|h| h.trim().strip_prefix("ref: ").map(str::to_string))
    {
        // A branch ref lives in the SHARED dir (a worktree's own dir has only
        // its HEAD and logs), which in an ordinary checkout is `.git` as well.
        let target = format!("{common_dir}/{target}");
        let target = Path::new(&target);
        if target.exists() {
            println!("cargo:rerun-if-changed={}", target.display());
        }
        // The loose ref file may not exist at build time: after `git pack-refs`
        // (which `git gc --auto` runs) git deletes it AND prunes its now-empty
        // directory, then the next commit recreates both. A watch on a path
        // that is missing registers nothing, so watch the nearest ancestor that
        // DOES exist (`.git/refs/heads` at worst) — a directory watch sees its
        // direct children appear, which is exactly the recreating step.
        if let Some(anc) = target.ancestors().skip(1).find(|a| a.exists()) {
            println!("cargo:rerun-if-changed={}", anc.display());
        }
    }

    let head = git(&["rev-parse", "HEAD"]).filter(|s| s.len() == 40);
    let override_sha = std::env::var("HSE_BUILD_SHA")
        .ok()
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty());

    let sha = override_sha
        .clone()
        .or_else(|| head.clone())
        .unwrap_or_else(|| "unknown".to_string());

    // Only claim a build is clean when we actually looked, and only when the
    // revision we are stamping is the one the tree is actually at. An override
    // that disagrees with HEAD is unverifiable by construction, and asserting
    // clean there would let a modified tree masquerade as the pristine revision
    // the SHA names — which is precisely the confusion this stamp exists to end.
    let dirty = match git(&["status", "--porcelain", "--untracked-files=no"]) {
        Some(s) if !s.is_empty() => "1",
        Some(_) => match (&override_sha, &head) {
            (Some(o), Some(h)) if o != h => "unknown",
            _ => "0",
        },
        // git absent, or not a repository (a source-archive build).
        None => "unknown",
    };

    println!("cargo:rustc-env=HSE_GIT_SHA={sha}");
    println!("cargo:rustc-env=HSE_GIT_DIRTY={dirty}");
}

/// Recursively collect `*.rs` files under `dir` as (path-with-forward-slashes,
/// line_count), and declare each visited directory + file as a `rerun-if-changed`
/// input so the manifest is regenerated on any source change at any depth.
fn collect(dir: &Path, out: &mut Vec<(String, u32)>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    // Watch this directory so a file added/removed directly under it reruns us.
    println!("cargo:rerun-if-changed={}", dir.display());
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            // Watch this file so a content change reruns us (a directory watch
            // alone does NOT catch edits to files in subdirectories).
            println!("cargo:rerun-if-changed={}", path.display());
            let lines = std::fs::read_to_string(&path).map_or(0, |s| s.lines().count() as u32);
            // Normalise to forward slashes for a stable, readable key.
            let rel = path.to_string_lossy().replace('\\', "/");
            out.push((rel, lines));
        }
    }
}

/// Directories whose files can change what a module answers: the crate's own
/// sources, including the data they embed (`include_str!`/`include_bytes!` — the
/// public suffix list, the OUI registry), and `hse-core`, the entity model every
/// module normalises through. [`is_module_logic`] filters out what cannot.
const LOGIC_ROOTS: &[&str] = &["src", "hse-core/src"];

/// Single files outside [`LOGIC_ROOTS`] that are module logic too: the exact
/// version of every dependency a module parses with.
const LOGIC_FILES: &[&str] = &["Cargo.lock"];

/// FNV-1a 64 offset basis and prime (draft-eastlake-fnv).
const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
const FNV_PRIME: u64 = 0x0100_0000_01b3;

/// The inter-scan cache's logic fingerprint (REQ-CACHE-002): FNV-1a 64 over the
/// sorted `(path, contents)` of every module-logic file.
///
/// `core::engine::dispatch::archive_key` prefixes it to every cache key. Without
/// it the key was `module:kind:value` alone, so after an upgrade a module's
/// PRE-fix answer was replayed until its TTL lapsed (a week for `builtwith`),
/// silently restoring the defect the upgrade fixed. It hashes content, not the
/// commit: a docs- or test-only commit leaves every cache warm, and a prebuilt
/// and a source build of the same tree share one cache.
///
/// Each file contributes its path, a NUL, its length (u64 LE) and its bytes, so
/// two different trees never present the same byte stream; sorting by path makes
/// the value independent of `read_dir` order. A listed file that cannot be read
/// fails the build (rustc must read it too) rather than be skipped into a value
/// that could equal the previous build's. `src/lib_tests.rs` re-derives the
/// value from the tree on disk.
fn logic_fingerprint() -> u64 {
    let mut inputs: Vec<(String, PathBuf)> = Vec::new();
    for root in LOGIC_ROOTS {
        collect_logic(Path::new(root), &mut inputs);
    }
    for file in LOGIC_FILES {
        if Path::new(file).is_file() {
            println!("cargo:rerun-if-changed={file}");
            inputs.push(((*file).to_string(), PathBuf::from(*file)));
        }
    }
    inputs.sort();
    let mut hash = FNV_OFFSET;
    for (rel, path) in &inputs {
        let bytes = std::fs::read(path).unwrap_or_else(|e| panic!("read {rel}: {e}"));
        hash = fnv1a(hash, rel.as_bytes());
        hash = fnv1a(hash, &[0]);
        hash = fnv1a(hash, &(bytes.len() as u64).to_le_bytes());
        hash = fnv1a(hash, &bytes);
    }
    hash
}

/// Fold `bytes` into an FNV-1a 64 `hash`.
fn fnv1a(mut hash: u64, bytes: &[u8]) -> u64 {
    for &b in bytes {
        hash ^= u64::from(b);
        hash = hash.wrapping_mul(FNV_PRIME);
    }
    hash
}

/// Recursively collect every module-logic file under `dir` as (path with forward
/// slashes, path), watching each directory and file exactly as [`collect`] does.
fn collect_logic(dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    println!("cargo:rerun-if-changed={}", dir.display());
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_logic(&path, out);
            continue;
        }
        let rel = path.to_string_lossy().replace('\\', "/");
        if is_module_logic(&rel) {
            println!("cargo:rerun-if-changed={}", path.display());
            out.push((rel, path));
        }
    }
}

/// Whether the file at `rel` (forward slashes) can change what a module answers.
/// Everything under [`LOGIC_ROOTS`] can, except:
/// - test material, by the repo's own conventions for it: `tests.rs`,
///   `*_tests.rs`, `test_*` support files (`test_support.rs`, `test_server.rs`,
///   `test_psl.txt`), and anything under a `tests/` or `testdata/` directory;
/// - `src/web/`, the browser UI, served verbatim and never read by a module.
///
/// Nothing else is excluded — not even a stray dotfile (an editor swap file).
/// Over-inclusion only cools the cache one extra time; under-inclusion is the
/// defect this fingerprint exists to close, so the rule errs toward hashing.
fn is_module_logic(rel: &str) -> bool {
    let (dirs, name) = rel.rsplit_once('/').unwrap_or(("", rel));
    let test_material = name == "tests.rs"
        || name.ends_with("_tests.rs")
        || name.starts_with("test_")
        || dirs.split('/').any(|d| d == "tests" || d == "testdata");
    !(test_material || rel.starts_with("src/web/"))
}
